import type { Metadata } from "next";
import { connection } from "next/server";
import { Suspense } from "react";
import { CallPlayer } from "@/components/calls/CallPlayer";
import { PageShell } from "@/components/SiteHeader";
import { CALLS, callOfDay } from "@/lib/calls";
import { dayKey } from "@/lib/dayKey";
import { getT } from "@/lib/i18n-server";
import { getCurrentUser } from "@/lib/server/session";
import { alternatesFor } from "@/lib/seo";

export async function generateMetadata(): Promise<Metadata> {
  const { t } = await getT();
  return {
    alternates: await alternatesFor("/llamadas"),
    title: t("Llamadas de estafa (vishing): practica qué responder", "Scam calls (vishing): practice what to say"),
    description: t(
      "Simulador de vishing con voz: recibe una llamada que puede ser estafa o real, practica qué decir y aprende a frenar el fraude bancario por teléfono. Sin riesgo.",
      "A voice vishing simulator: get a call that may be a scam or real, practice what to say and learn to stop bank fraud over the phone. Risk-free.",
    ),
  };
}

async function Player() {
  // La llamada gratuita cambia cada día: siempre por petición
  await connection();
  const user = await getCurrentUser();
  const unlocked = user?.isPro ? CALLS.map((c) => c.id) : [callOfDay(dayKey()).id];
  return <CallPlayer unlocked={unlocked} loggedIn={!!user} isPro={!!user?.isPro} />;
}

export default async function LlamadasPage() {
  const { t } = await getT();
  return (
    <PageShell>
      <div className="mx-auto max-w-4xl">
        <span className="eyebrow">{t("Práctica de vishing", "Vishing practice")}</span>
        <h1 className="mt-2 font-display text-4xl sm:text-5xl">{t("¿Qué harías si te llaman?", "What would you do if they called?")}</h1>
        <p className="mb-10 mt-3 max-w-2xl text-lg text-fog">
          {t(
            "Muchas estafas llegan por teléfono, pero no toda llamada es una estafa. Contesta, escucha y elige qué responder. Al terminar, decide si era una estafa o una llamada real: el XP depende de que aciertes. Gratis: una llamada distinta cada día; con Pro, llamadas aleatorias.",
            "Many scams arrive by phone, but not every call is a scam. Answer, listen and choose what to reply. When it ends, decide whether it was a scam or a real call: your XP depends on getting it right. Free: a different call every day; with Pro, random calls.",
          )}
        </p>
        <Suspense fallback={<div className="h-72 animate-pulse rounded-3xl bg-desk-3" />}>
          <Player />
        </Suspense>
        <p className="mt-8 text-xs text-fog">
          {t(
            "La voz la genera tu propio navegador: no grabamos ni enviamos audio. Los nombres, bancos y números son ficticios.",
            "The voice is generated by your own browser: we don't record or send any audio. Names, banks and numbers are fictional.",
          )}
        </p>
      </div>
    </PageShell>
  );
}
